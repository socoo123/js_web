import { products } from "../../shared/products.js";
import { Inventory, createCategoryFilter } from "./inventory.js";
import { categoryTree, walkDepthFirst, walkBreadthFirst } from "./tree.js";

const inventory = new Inventory(products);
const isPeripheral = createCategoryFilter("外设");
const isAccessory = createCategoryFilter("配件");
const peripherals = inventory.select(isPeripheral).map(product => product.id);
const accessories = inventory.select(isAccessory).map(product => product.id);
console.log("外设：", peripherals.join(", "));
console.log("配件：", accessories.join(", "));
console.log("原始商品数：", inventory.count());
const selectAccessories = inventory.select.bind(inventory, isAccessory);
console.log("回调筛选配件：", selectAccessories().length);
console.log("实例自有 select：", Object.hasOwn(inventory, "select"));
console.log("独立空库存：", new Inventory([]).count());
const byStock = inventory.sorted((a, b) => a.stock - b.stock);
console.log("库存升序：", byStock.map(product => product.id).join(", "));
console.log("原始顺序：", inventory.select(() => true).map(product => product.id).join(", "));
const summary = inventory.summary();
console.log("总库存：", summary.totalStock);
console.log("库存总价值（分）：", summary.totalValueCents);
console.log("售罄 / 低库存：", summary.soldOutCount, summary.lowStockCount);
console.log("空库存统计：", JSON.stringify(new Inventory([]).summary()));
const dock = inventory.getById("P004");
console.log("按 id 查找：", dock.id, dock.name, dock.stock);
console.log("缺失商品：", inventory.getById("P999"));
const groups = inventory.groupedByCategory();
console.log("分类种数：", groups.size);
for (const [category, group] of groups) console.log("分类：", category, group.length);
console.log("去重标签：", inventory.uniqueTags().join(", "));
const empty = new Inventory([]);
console.log("空库存索引 / 分组 / 标签：", empty.getById("P001"), empty.groupedByCategory().size, empty.uniqueTags().length);
const editable = new Inventory(products.map(product => ({ ...product, tags: [...product.tags] })));
const tasks = [{ id: "P002", stock: 3 }, { id: "P004", stock: 6 }];
const completed = [];
for (let head = 0; head < tasks.length; head++) {
  const { id, stock } = tasks[head];
  editable.setStock(id, stock);
  completed.push(id);
}
console.log("任务执行：", completed.join(", "));
console.log("修改库存：", editable.getById("P002").stock, editable.getById("P004").stock);
console.log("撤销一次：", editable.undo(), editable.getById("P004").stock);
console.log("撤销两次：", editable.undo(), editable.getById("P002").stock);
console.log("历史耗尽：", editable.undo());
console.log("撤销后总库存：", editable.summary().totalStock);
const navigation = [];
walkDepthFirst(categoryTree, (node, depth) => navigation.push("  ".repeat(depth) + node.name));
console.log("分类导航：\n" + navigation.join("\n"));
const breadthNames = [];
walkBreadthFirst(categoryTree, node => breadthNames.push(node.name));
console.log("逐层分类：", breadthNames.join(" → "));
